"""Inline real product images into a Y10 page's IMG-DATA block.

Activities may only load shared files, so images travel inside the page as data URIs.
Each is shrunk (600 px wide by default, the size agreed for public pages) and saved as JPEG.

    python Y10/inline_images.py <page.html> key=file[@width | @fit<size>] ...

@fit<size> fits the image inside a size × size square instead, so portrait posters and
wide screenshots come out equally readable (sort cards use @fit440, so the zoom view is sharp).

Files are read from _presentations/Y10_BTEC_CDM/images/ (git-ignored originals). The page
gets window.IMG = { key: 'data:image/jpeg;base64,…' }; <img data-img="key"> and sort cards
with img: 'key' pick them up. Re-running replaces the whole block, and the command is kept
in the block's comment so it can be run again.
"""
import base64
import io
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / '_presentations' / 'Y10_BTEC_CDM' / 'images'
BLOCK = re.compile(r'<!-- IMG-DATA:.*?<!-- /IMG-DATA -->', re.S)


def encode(path, width):
    im = Image.open(path).convert('RGB')
    if width.startswith('fit'):
        scale = min(1, int(width[3:]) / max(im.size))
    else:
        scale = min(1, int(width) / im.width)
    if scale < 1:
        im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'JPEG', quality=78, optimize=True, progressive=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()


def main(page, specs):
    html = Path(page).read_text(encoding='utf-8')
    if not BLOCK.search(html):
        sys.exit(f'{page}: no <!-- IMG-DATA: … --> … <!-- /IMG-DATA --> block')
    lines = []
    for spec in specs:
        key, _, rest = spec.partition('=')
        name, _, width = rest.partition('@')
        lines.append(f'  {key!r}: {encode(SRC / name, width or '600')!r},')
    block = ('<!-- IMG-DATA: generated by Y10/inline_images.py, do not edit by hand. Rebuild with:\n'
             f'     python Y10/inline_images.py {page} {" ".join(specs)} -->\n'
             '<script>window.IMG = {\n' + '\n'.join(lines) + '\n};</script>\n<!-- /IMG-DATA -->')
    Path(page).write_text(BLOCK.sub(lambda _: block, html, count=1), encoding='utf-8')
    print(f'{page}: {len(specs)} images, {len(block) // 1024} KB')


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2:])
